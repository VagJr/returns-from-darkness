"""Inspect and pack the user-provided PNGs; never repaint or alter the source kit."""
from pathlib import Path
from PIL import Image
import json, hashlib, shutil, argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'content/original/hud-kit/source'
parser=argparse.ArgumentParser()
parser.add_argument('--source',type=Path)
parser.add_argument('--engine-root',type=Path,default=ROOT/'candidates/thehell3')
args=parser.parse_args()
download=Path('C:/Users/vagmi/Downloads/Dark_Gothic_HUD_Kit/Dark_Gothic_HUD_Kit')
INPUT=args.source or (download if download.exists() else SOURCE)
OUT = ROOT/'content/original/ui/gothic-kit'
SOURCE.mkdir(parents=True, exist_ok=True); OUT.mkdir(parents=True, exist_ok=True)
manifest = json.loads((INPUT/'asset_manifest.json').read_text(encoding='utf-8'))
inspected=[]
for p in sorted(INPUT.rglob('*.png')):
    im=Image.open(p).convert('RGBA')
    inspected.append(dict(file=p.relative_to(INPUT).as_posix(), size=list(im.size),
                          alpha=list(im.getchannel('A').getextrema()),
                          visibleBox=im.getchannel('A').getbbox(), sha256=hashlib.sha256(p.read_bytes()).hexdigest()))
    dest=SOURCE/p.relative_to(INPUT); dest.parent.mkdir(parents=True, exist_ok=True)
    if p.resolve()!=dest.resolve(): shutil.copy2(p,dest)
for name in ('asset_manifest.json','LEIA-ME_PTBR.md'):
    if (INPUT/name).resolve()!=(SOURCE/name).resolve(): shutil.copy2(INPUT/name,SOURCE/name)
selected=[
 ('HUD','01_PAINEIS/hud_inferior_completo.png'),
 ('CHAR_FRAME','02_MOLDURAS/moldura_personagem_sobreposta.png'),
 ('INV_FRAME','02_MOLDURAS/moldura_inventario_sobreposta.png'),
 ('MESSAGE','05_ORBES_BARRAS/painel_mensagens_hud.png'),
 ('SLOT','03_SLOTS/slot_equipamento_quadrado.png'),
 ('TALL_SLOT','03_SLOTS/slot_vertical_longo.png'),
 ('BUTTON','04_BOTOES_ICONS/botao_horizontal_A.png'),
 ('CROWN','04_BOTOES_ICONS/ornamento_cabeca_demonio.png'),
 ('SEAL','04_BOTOES_ICONS/medalhao_pentagrama.png'),
 ('ROMAN_I','04_BOTOES_ICONS/botao_romano_I.png'),
 ('ROMAN_II','04_BOTOES_ICONS/botao_romano_II.png'),
 ('ROMAN_III','04_BOTOES_ICONS/botao_romano_III.png'),
 ('GRID_CELL','01_PAINEIS/painel_inventario_vazio_editavel.png'),
 ('HOTBAR_FRAME','02_MOLDURAS/faixa_botoes_vazia.png'),
 ('GOLD_WELL','02_MOLDURAS/moldura_inventario_sobreposta.png'),
]
for key,name in [('TL','superior_esquerdo'),('TC','superior_centro'),('TR','superior_direito'),
                 ('ML','meio_esquerdo'),('C','centro'),('MR','meio_direito'),
                 ('BL','inferior_esquerdo'),('BC','inferior_centro'),('BR','inferior_direito')]:
    selected.append(('FRAME_'+key,'06_NINE_SLICE/frame9_'+name+'.png'))
atlas=Image.new('RGBA',(2048,2048)); x=y=2; shelf=0; rects=[]
# Large rectangles first; stable shelf packing with transparent gutters.
images=[]
for key,name in selected:
    im=Image.open(SOURCE/name).convert('RGBA')
    if key=='GRID_CELL': im=im.crop((62,355,102,400))
    if key=='GOLD_WELL': im=im.crop((142,622,178,639))
    images.append((key,name,im))
images.sort(key=lambda v:(-v[2].height,-v[2].width))
for key,name,im in images:
    if x+im.width+2>2048: x=2;y+=shelf+4;shelf=0
    assert y+im.height+2<=2048, 'Atlas exceeded the renderer budget'
    atlas.paste(im,(x,y));rects.append(dict(id=key,file=name,xywh=[x,y,*im.size]))
    x+=im.width+4;shelf=max(shelf,im.height)
atlas.save(OUT/'hud-atlas.png',optimize=True)
rows={row['id']:row for row in rects}
header=['#pragma once','// Packed original user PNGs; generated by prepare-gothic-hud-kit.py.',
        'enum RfdKitAsset { '+', '.join('KIT_'+key for key,_ in selected)+', KIT_ASSET_COUNT };',
        'struct RfdKitSource { int x,y,w,h; };','static const RfdKitSource RfdKitSources[KIT_ASSET_COUNT] = {']
header+=[' {'+','.join(map(str,rows[key]['xywh']))+'}, // '+key for key,_ in selected]
header+=['};',''];(args.engine_root/'src/CommunityHudAtlas.h').write_text('\n'.join(header),encoding='utf-8')
report=dict(source='User-provided Dark Gothic HUD Kit 1.0',sourceCanvas=manifest['source_canvas_size'],
            filesInspected=inspected,atlasSize=[2048,2048],atlasSha256=hashlib.sha256((OUT/'hud-atlas.png').read_bytes()).hexdigest(),
            sprites=rects,sourceArtworkModified=False,
            corrections=['The sample inventory has 10x5 cells; the native inventory retains 10x7.',
                         'The blue glass center is approximately (112,98), not the manifest (94,98).',
                         'Illustrative fixed items, numerical fields and potion pictures are not runtime game state.'])
(ROOT/'content/original/hud-kit/integration.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps(dict(passed=True,inspected=len(inspected),packed=len(rects),atlasSize=[2048,2048],sourceArtworkModified=False)))
